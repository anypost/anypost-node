// Regenerates src/version.ts from package.json so the SDK version lives in one
// place. Runs automatically before `build` and `test` (see package.json), and
// can be run directly with `bun run sync-version`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const contents = `// Generated by scripts/sync-version.mjs — do not edit by hand.
// The version is single-sourced from package.json; run \`bun run sync-version\`.
export const SDK_VERSION = "${version}";
`;

writeFileSync(join(root, "src", "version.ts"), contents);
console.log(`src/version.ts -> ${version}`);
